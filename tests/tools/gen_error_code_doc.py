#!/usr/bin/env python3
"""Generate the bilingual API error reference from locale catalogs and code."""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path


ERROR_PREFIX = "error."
TASK_FAILURE_PREFIX = "error.task_failure."
HEADER = """<!-- Generated by tests/tools/gen_error_code_doc.py. Do not edit by hand. -->
<!-- Regenerate: uv run python tests/tools/gen_error_code_doc.py > docs/guides/api/error-codes.md -->

# API 错误码参考 / API Error Code Reference

本文档由脚本生成，请勿手动编辑。修改语言文案或错误调用后运行：
`uv run python tests/tools/gen_error_code_doc.py > docs/guides/api/error-codes.md`。

This document is generated by a script; do not edit it by hand. After changing locale
strings or API error calls, run the command above.

## HTTP API 错误码 / HTTP API error codes

HTTP 状态来自生产代码中的 `ApiError(status, error_code)` 调用。`dynamic: status`
表示该调用在运行时决定状态码。

| error_code | HTTP 状态 / HTTP status | zh-CN 文案 | en 文案 |
|---|---:|---|---|
"""


def _error_call(node: ast.Call) -> bool:
    function = node.func
    return (isinstance(function, ast.Name) and function.id == "ApiError") or (
        isinstance(function, ast.Attribute) and function.attr == "ApiError"
    )


def _status_label(node: ast.expr) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, int) and not isinstance(node.value, bool):
        return str(node.value)
    return f"dynamic: {ast.unparse(node)}"


def extract_api_errors(source_root: Path) -> dict[str, set[str]]:
    """Extract literal error codes and their status arguments from production AST."""
    codes: dict[str, set[str]] = {}
    source_dir = source_root / "src" / "video_transcript_api"
    for path in sorted(source_dir.rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call) or not _error_call(node) or len(node.args) < 2:
                continue
            code = node.args[1]
            if isinstance(code, ast.Constant) and isinstance(code.value, str):
                codes.setdefault(code.value, set()).add(_status_label(node.args[0]))
    return codes


def _table_text(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", "<br>")


def _locale_values(source_root: Path) -> tuple[dict[str, str], dict[str, str]]:
    locale_dir = source_root / "src" / "video_transcript_api" / "i18n" / "locales"
    zh_cn = json.loads((locale_dir / "zh-CN.json").read_text(encoding="utf-8"))
    en = json.loads((locale_dir / "en.json").read_text(encoding="utf-8"))
    if set(zh_cn) != set(en):
        missing_en = sorted(set(zh_cn) - set(en))
        missing_zh = sorted(set(en) - set(zh_cn))
        raise ValueError(f"locale key sets differ: missing en={missing_en}, missing zh-CN={missing_zh}")
    for key in zh_cn:
        if not isinstance(zh_cn[key], str) or not isinstance(en[key], str):
            raise TypeError(f"locale values must be strings: {key}")
    return zh_cn, en


def render_document(source_root: Path) -> str:
    zh_cn, en = _locale_values(source_root)
    api_errors = extract_api_errors(source_root)
    missing_locales = sorted(f"{ERROR_PREFIX}{code}" for code in api_errors if f"{ERROR_PREFIX}{code}" not in zh_cn)
    if missing_locales:
        raise ValueError(f"ApiError codes missing locale entries: {missing_locales}")

    lines = [HEADER.rstrip()]
    for code, statuses in sorted(api_errors.items()):
        key = f"{ERROR_PREFIX}{code}"
        status = ", ".join(sorted(statuses))
        lines.append(
            f"| `{code}` | {status} | {_table_text(zh_cn[key])} | {_table_text(en[key])} |"
        )

    task_failure_keys = sorted(key for key in zh_cn if key.startswith(TASK_FAILURE_PREFIX))
    lines.extend(
        [
            "",
            "## 任务失败原因 / Task failure reasons",
            "",
            "以下 `error.task_failure.*` key 出现在 `GET /api/task/{task_id}` 响应的 `data.error`，不是 HTTP 错误体的 `error_code`。异常原文可作为占位符值保留在文案中。",
            "",
            "The `error.task_failure.*` keys below appear in `data.error` in the `GET /api/task/{task_id}` response; they are not `error_code` values in an HTTP error body. Exception text may be preserved as placeholder values.",
            "",
            "| key | zh-CN 文案 | en 文案 |",
            "|---|---|---|",
        ]
    )
    for key in task_failure_keys:
        lines.append(f"| `{key}` | {_table_text(zh_cn[key])} | {_table_text(en[key])} |")

    http_locale_keys = {f"{ERROR_PREFIX}{code}" for code in api_errors}
    task_failure_set = set(task_failure_keys)
    other_error_keys = sorted(
        key for key in zh_cn if key.startswith(ERROR_PREFIX) and key not in http_locale_keys and key not in task_failure_set
    )
    if other_error_keys:
        lines.extend(
            [
                "",
                "## 其他本地化错误文案 / Other localized error strings",
                "",
                "以下目录项用于任务状态中的通用失败文案或状态清理附注，不是 HTTP `error_code`。",
                "",
                "These catalog entries are generic task-status failure text or status-cleanup notes, not HTTP `error_code` values.",
                "",
                "| locale key | zh-CN 文案 | en 文案 |",
                "|---|---|---|",
            ]
        )
        for key in other_error_keys:
            lines.append(f"| `{key}` | {_table_text(zh_cn[key])} | {_table_text(en[key])} |")

    lines.extend(
        [
            "",
            "## 说明 / Notes",
            "",
            "FastAPI 请求体校验产生的 422 响应保留默认形状，不含 `error_code`。应用处理器对其他 Starlette HTTP 错误可能附加 `resource_not_found`、`method_not_allowed` 或 `api_error`；这些框架错误保留原始 `detail`，不属于 locale 文案表。",
            "",
            "FastAPI request-validation 422 responses keep their default shape and do not include `error_code`. The application handler may attach `resource_not_found`, `method_not_allowed`, or `api_error` to other Starlette HTTP errors; their original `detail` is preserved, so they are not locale strings listed above.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        help=argparse.SUPPRESS,
    )
    args = parser.parse_args()
    source_root = args.root.resolve() if args.root else Path(__file__).resolve().parents[2]
    sys.stdout.write(render_document(source_root))


if __name__ == "__main__":
    main()
